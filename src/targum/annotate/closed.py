#: is also why a form that would be a different word with its first letter read as a
#: prefix is written whole: `בית` is a house before it is ב + `ית`.
#:
#: **Left out on purpose**: forms that are two common words at once and a reader could be
#: looking at either. `עמי` is "with me" in Genesis and "my people" all through Exodus;
#: `שנא` is a tooth and a year; `קימא` is a covenant and the Living One. A wrong answer on
#: a card is worse than none, so those go to the dictionary and are left without a meaning
#: where it is not sure.
#:
#: The headwords are pointed the way Onkelos is, and a verb is filed under its perfect,
